package postgres

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"strconv"
	"strings"
	"time"

	"tusk/internal/db"
)

type editColumn struct {
	name     string
	key      bool
	readOnly bool
}

func (s *session) editColumns(ctx context.Context, schema, table string) ([]editColumn, db.TableEditInfo, error) {
	info := db.TableEditInfo{KeyColumns: []string{}, ReadOnlyColumns: []string{}}
	rows, err := s.conn.Query(ctx, `
		SELECT c.relkind::text, a.attname,
		       EXISTS (SELECT 1 FROM pg_catalog.pg_index i
		               WHERE i.indrelid=c.oid AND i.indisprimary AND a.attnum=ANY(i.indkey)),
		       a.attgenerated <> '' OR a.attidentity <> ''
		FROM pg_catalog.pg_class c
		JOIN pg_catalog.pg_namespace n ON n.oid=c.relnamespace
		JOIN pg_catalog.pg_attribute a ON a.attrelid=c.oid
		WHERE n.nspname=$1 AND c.relname=$2 AND a.attnum>0 AND NOT a.attisdropped
		ORDER BY a.attnum`, schema, table)
	if err != nil {
		return nil, info, queryError(ctx, err)
	}
	defer rows.Close()
	columns := []editColumn{}
	for rows.Next() {
		var kind string
		var column editColumn
		if err := rows.Scan(&kind, &column.name, &column.key, &column.readOnly); err != nil {
			return nil, info, queryError(ctx, err)
		}
		if kind != "r" && kind != "p" {
			info.Reason = "Only tables can be edited. Views and foreign tables are read-only"
		}
		columns = append(columns, column)
		if column.key {
			info.KeyColumns = append(info.KeyColumns, column.name)
		}
		if column.readOnly {
			info.ReadOnlyColumns = append(info.ReadOnlyColumns, column.name)
		}
	}
	if err := rows.Err(); err != nil {
		return nil, info, queryError(ctx, err)
	}
	if len(columns) == 0 {
		info.Reason = "The table was not found. Refresh the database navigation"
	} else if len(info.KeyColumns) == 0 && info.Reason == "" {
		info.Reason = "This table needs a primary key before rows can be edited or removed"
	}
	return columns, info, nil
}

func (s *session) TableEditInfo(ctx context.Context, schema, table string) (db.TableEditInfo, error) {
	_, info, err := s.editColumns(ctx, schema, table)
	return info, err
}

func (s *session) SaveTableChanges(ctx context.Context, schema, table string, names []string, changes []db.RowChange) (int, error) {
	if err := db.ValidateChanges(names, changes); err != nil {
		return 0, err
	}
	// Save must own its transaction instead of committing a transaction entered in the SQL editor.
	if s.conn.PgConn().TxStatus() != 'I' {
		return 0, errors.New("Finish the SQL editor transaction with COMMIT or ROLLBACK before saving table changes")
	}
	tx, err := s.conn.Begin(ctx)
	if err != nil {
		return 0, queryError(ctx, err)
	}
	defer func() {
		rollbackCtx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
		defer cancel()
		_ = tx.Rollback(rollbackCtx)
	}()
	qualified := db.QuoteIdentifier(schema) + "." + db.QuoteIdentifier(table)
	// Prevent schema changes between metadata validation and the mutations.
	if _, err := tx.Exec(ctx, "LOCK TABLE "+qualified+" IN ROW EXCLUSIVE MODE"); err != nil {
		return 0, queryError(ctx, err)
	}
	columns, info, err := s.editColumns(ctx, schema, table)
	if err != nil {
		return 0, err
	}
	if info.Reason != "" {
		return 0, errors.New(info.Reason)
	}
	known := make(map[string]bool, len(columns))
	for _, column := range columns {
		known[column.name] = true
	}
	indices := make(map[string]int, len(names))
	quotedNames := make([]string, len(names))
	for i, name := range names {
		if !known[name] {
			return 0, errors.New("The table columns changed. Undo changes, refresh the table, and try again")
		}
		indices[name] = i
		quotedNames[i] = db.QuoteIdentifier(name)
	}
	for _, column := range columns {
		if column.key {
			if _, ok := indices[column.name]; !ok {
				return 0, errors.New("Include every primary-key column in the SELECT result before editing or removing rows")
			}
		}
	}
	seen := map[string]bool{}
	for _, change := range changes {
		key := []*string{}
		for _, column := range columns {
			if _, changing := change.Values[column.name]; changing && column.readOnly {
				return 0, fmt.Errorf("%s is generated by the database and cannot be edited", column.name)
			}
			if column.key {
				if change.Original[indices[column.name]] == nil {
					return 0, errors.New("Rows with a NULL primary key cannot be edited")
				}
				key = append(key, change.Original[indices[column.name]])
			}
		}
		encoded, _ := json.Marshal(key)
		if seen[string(encoded)] {
			return 0, errors.New("The same row appears more than once. Undo changes and try again")
		}
		seen[string(encoded)] = true
	}
	for rowIndex, change := range changes {
		keyParams := [][]byte{}
		conditions := []string{}
		for _, column := range columns {
			if column.key {
				keyParams = append(keyParams, []byte(*change.Original[indices[column.name]]))
				conditions = append(conditions, db.QuoteIdentifier(column.name)+"=$"+strconv.Itoa(len(keyParams)))
			}
		}
		where := " WHERE " + strings.Join(conditions, " AND ")
		reader := s.conn.PgConn().ExecParams(ctx, "SELECT "+strings.Join(quotedNames, ", ")+" FROM "+qualified+where+" FOR UPDATE", keyParams, nil, nil, nil)
		matches, rowCount := true, 0
		for reader.NextRow() {
			rowCount++
			values := reader.Values()
			if len(values) != len(change.Original) {
				matches = false
				continue
			}
			for i, original := range change.Original {
				if original == nil && values[i] != nil || original != nil && (values[i] == nil || *original != string(values[i])) {
					matches = false
				}
			}
		}
		if _, err := reader.Close(); err != nil {
			return 0, queryError(ctx, err)
		}
		if !matches || rowCount != 1 {
			return 0, fmt.Errorf("Row %d changed or was removed since it was loaded. No changes were saved. Undo changes, refresh the table, and try again", rowIndex+1)
		}
		params := append([][]byte{}, keyParams...)
		statement := "DELETE FROM " + qualified
		if !change.Delete {
			assignments := []string{}
			for _, column := range columns {
				if value, ok := change.Values[column.name]; ok {
					var encoded []byte
					if value != nil {
						encoded = []byte(*value)
					}
					params = append(params, encoded)
					assignments = append(assignments, db.QuoteIdentifier(column.name)+"=$"+strconv.Itoa(len(params)))
				}
			}
			statement = "UPDATE " + qualified + " SET " + strings.Join(assignments, ", ")
		}
		reader = s.conn.PgConn().ExecParams(ctx, statement+where, params, nil, nil, nil)
		tag, err := reader.Close()
		if err != nil {
			return 0, queryError(ctx, err)
		}
		if tag.RowsAffected() != 1 {
			return 0, fmt.Errorf("Row %d could not be saved. No changes were saved. Check your permissions and refresh the table", rowIndex+1)
		}
	}
	if err := tx.Commit(ctx); err != nil {
		return 0, queryError(ctx, err)
	}
	return len(changes), nil
}
